"""Structural types shared by the Chrome and Camoufox engines.

The MCP server, scorecard, warmup and fingerprint capture only need this much
of a browser. Both :class:`disguisebrowser.browser.Browser` (Chrome over quiet
CDP) and :class:`disguisebrowser.camoufox.CamoufoxBrowser` (Camoufox over
Playwright/Juggler) satisfy it, so the layers above never branch on the engine.
"""

from __future__ import annotations

from collections.abc import Sequence
from contextlib import AbstractAsyncContextManager
from pathlib import Path
from typing import TYPE_CHECKING, Any, Literal, Protocol, runtime_checkable

if TYPE_CHECKING:
    import random

    from disguisebrowser.display import VirtualDisplay
    from disguisebrowser.exchange import Download, HttpResponse, JsDialog, Pending
    from disguisebrowser.persona import Persona
    from disguisebrowser.proxy import GeoInfo, ProxyGateway
    from disguisebrowser.snapshot import Snapshot
    from disguisebrowser.warmup import WarmupVisit

Engine = Literal["chrome", "camoufox"]
WaitUntil = Literal["commit", "domcontentloaded", "load", "networkidle"]
World = Literal["isolated", "main"]


class KeyboardLike(Protocol):
    async def press(self, key: str, *, humanize: bool = True) -> None: ...


class ElementLike(Protocol):
    async def text(self) -> str: ...
    async def outer_html(self) -> str: ...
    async def hover(self, *, humanize: bool = True) -> None: ...
    async def click(self, *, humanize: bool = True) -> None: ...
    async def type(self, text: str, *, humanize: bool = True, clear: bool = False) -> None: ...
    async def set_input_files(self, *paths: str | Path) -> None: ...


@runtime_checkable
class PageLike(Protocol):
    dialog_action: Literal["dismiss", "accept"]
    dialog_prompt: str

    @property
    def url(self) -> str: ...
    @property
    def closed(self) -> bool: ...
    @property
    def rng(self) -> random.Random: ...
    @property
    def keyboard(self) -> KeyboardLike: ...

    async def close(self) -> None: ...
    async def goto(
        self, url: str, *, wait_until: WaitUntil = "load", timeout: float = 30.0
    ) -> None: ...
    async def go_back(self, *, wait_until: WaitUntil = "load", timeout: float = 30.0) -> bool: ...
    async def wait_for_timeout(self, ms: float) -> None: ...
    async def bring_to_front(self) -> None: ...
    async def activate(self) -> None: ...
    async def evaluate(self, expression: str, *, world: World = "isolated") -> Any: ...
    async def call(self, function: str, *args: Any, world: World = "isolated") -> Any: ...
    async def wait_for_selector(
        self,
        selector: str,
        *,
        timeout: float = 30.0,
        state: Literal["attached", "visible", "hidden"] = "attached",
    ) -> ElementLike | None: ...
    async def snapshot(self, *, max_lines: int = 400) -> Snapshot: ...
    async def element_by_ref(self, ref: str) -> ElementLike: ...
    async def content(self) -> str: ...
    async def title(self) -> str: ...
    async def scroll(self, delta_y: float, *, humanize: bool = True) -> None: ...
    def expect_dialog(
        self, *, timeout: float = 5.0
    ) -> AbstractAsyncContextManager[Pending[JsDialog]]: ...
    async def watch_responses(self) -> None: ...
    def responses(self) -> list[HttpResponse]: ...
    def expect_response(
        self, url_contains: str, *, timeout: float = 30.0
    ) -> AbstractAsyncContextManager[Pending[HttpResponse]]: ...
    def expect_download(
        self, *, timeout: float = 30.0
    ) -> AbstractAsyncContextManager[Pending[Download]]: ...
    async def screenshot(
        self,
        path: str | Path | None = None,
        *,
        full_page: bool = False,
        format: Literal["png", "jpeg", "webp"] = "png",
        quality: int | None = None,
    ) -> bytes: ...


@runtime_checkable
class BrowserLike(Protocol):
    @property
    def engine(self) -> str: ...
    @property
    def persona(self) -> Persona: ...
    @property
    def version(self) -> dict[str, Any]: ...
    @property
    def pages(self) -> Sequence[PageLike]: ...
    @property
    def display(self) -> VirtualDisplay | None: ...
    @property
    def gateway(self) -> ProxyGateway | None: ...
    @property
    def geo(self) -> GeoInfo | None: ...
    @property
    def input_mode(self) -> str: ...
    @property
    def closed(self) -> bool: ...

    async def new_page(self, url: str = "about:blank", **goto_kwargs: Any) -> PageLike: ...
    async def warmup(
        self,
        urls: list[str] | None = None,
        *,
        count: int = 3,
        dwell: tuple[float, float] = (1.0, 2.5),
    ) -> list[WarmupVisit]: ...
    async def close(self) -> None: ...
